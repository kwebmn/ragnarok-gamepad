#!/usr/bin/env python3
"""Generate src/core/proto/packet_tables.cpp from uAthena sources.

S2C lengths: the hardcoded packet_len_table[] in src/map/clif.c (packet_db[SERVER], used by
             WFIFOSET when the map server sends), resolved for PACKETVER from src/map/clif.h.
C2S lengths: db/packet_db.txt applied in file order. Every 'packet_ver: N' line copies the
             previous version, so the last version (22) is the cumulative result.

Usage: python3 -I tools/gen_packet_tables.py /root/uar/uAthena src/core/proto/packet_tables.cpp
"""
import re
import sys

TABLE_SIZE = 0x300


def read_packetver(root):
    text = open(f"{root}/src/map/clif.h", encoding="latin-1").read()
    m = re.search(r"#\s*define\s+PACKETVER\s+(\d+)", text)
    if not m:
        sys.exit("PACKETVER not found in clif.h")
    return int(m.group(1))


def read_s2c(root, packetver):
    text = open(f"{root}/src/map/clif.c", encoding="latin-1").read()
    body = text.split("int packet_len_table[MAX_PACKET_DB] = {", 1)[1].split("};", 1)[0]
    values, active = [], []
    for raw in body.splitlines():
        line = raw.strip()
        m = re.match(r"#if\s+PACKETVER\s*(<=|>=|==|<|>)\s*(\d+)", line)
        if m:
            op, num = m.group(1), int(m.group(2))
            active.append({"<": packetver < num, "<=": packetver <= num, ">": packetver > num,
                           ">=": packetver >= num, "==": packetver == num}[op])
            continue
        if line.startswith("#else"):
            active[-1] = not active[-1]
            continue
        if line.startswith("#endif"):
            active.pop()
            continue
        if active and not all(active):
            continue
        line = line.split("//", 1)[0]
        values += [int(v) for v in re.findall(r"-?\d+", line)]
    if len(values) != TABLE_SIZE:
        sys.exit(f"expected {TABLE_SIZE} S2C entries, got {len(values)}")
    return values


def read_c2s(root):
    lens = [0] * TABLE_SIZE
    for raw in open(f"{root}/db/packet_db.txt", encoding="latin-1"):
        line = raw.split("//", 1)[0].strip()
        if not line.startswith("0x"):
            continue
        parts = line.split(",")
        cmd = int(parts[0], 16)
        if 0 < cmd < TABLE_SIZE and len(parts) >= 2:
            lens[cmd] = int(parts[1])
    return lens


def emit(name, values):
    rows = []
    for i in range(0, TABLE_SIZE, 16):
        rows.append("    " + ", ".join(f"{v:4d}" for v in values[i:i + 16]) + f",  // 0x{i:04x}")
    return f"const int16_t {name}[{TABLE_SIZE}] = {{\n" + "\n".join(rows) + "\n};\n"


def main():
    root, out = sys.argv[1], sys.argv[2]
    packetver = read_packetver(root)
    s2c, c2s = read_s2c(root, packetver), read_c2s(root)
    with open(out, "w") as f:
        f.write("// GENERATED by tools/gen_packet_tables.py from uAthena sources. Do not edit.\n")
        f.write(f"// Server PACKETVER = {packetver}; client table = db/packet_db.txt up to packet_ver 22.\n")
        f.write('#include "core/proto/packet_tables.hpp"\n\nnamespace uapad {\nnamespace {\n\n')
        f.write(emit("kS2C", s2c))
        f.write("\n")
        f.write(emit("kC2S", c2s))
        f.write("\n}  // namespace\n\n")
        f.write("int s2cLength(uint16_t id) { return id < 0x300 ? kS2C[id] : 0; }\n")
        f.write("int c2sLength(uint16_t id) { return id < 0x300 ? kC2S[id] : 0; }\n\n")
        f.write("}  // namespace uapad\n")


if __name__ == "__main__":
    main()
